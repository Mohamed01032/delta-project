def build_report(pred_class, probability, confidence, image_url=None, filename=None):
    risk = get_risk_level(pred_class, probability)
    meta = RISK_META[risk]
    sections = SECTIONS[risk]

    parkinson_pct = round(probability * 100)
    normal_pct = 100 - parkinson_pct
    confidence_pct = round(confidence * 100)

    return {
        "report_id": datetime.now().strftime("%Y%m%d-%H%M%S"),
        "date": datetime.now().strftime("%Y/%m/%d"),
        "time": datetime.now().strftime("%H:%M"),
        "risk_level": risk,
        "risk_title": meta["title"],
        "risk_badge": meta["badge"],
        "risk_color": meta["color"],
        "summary": meta["summary"],
        "pred_class": pred_class,
        "parkinson_pct": parkinson_pct,
        "normal_pct": normal_pct,
        "confidence_pct": confidence_pct,
        "image_url": image_url,
        "filename": filename or "—",
        "sections": sections,
    }
