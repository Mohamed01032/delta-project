SUSPICION_THRESHOLD = 0.30
PARKINSON_THRESHOLD = 0.927


def get_risk_level(pred_class, probability):
    if pred_class == "Parkinson":
        return "parkinson"
    if probability >= SUSPICION_THRESHOLD:
        return "suspicious"
    return "normal"


